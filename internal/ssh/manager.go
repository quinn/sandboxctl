// Manager owns sandboxctl's SSH keys and generated configuration.
type Manager struct {
	Paths config.Paths
}

// HostEntry contains the connection values for one managed sandbox.
type HostEntry struct {
	Name    string
	Address string
	User    string
}

// PrepareKey creates the private XDG directories and the operator SSH key.
func (m Manager) PrepareKey() error {
	if err := m.Paths.Ensure(); err != nil {
		return err
	}
	if err := m.ensureKey(); err != nil {
		return err
	}
	if err := ensureFile(m.Paths.KnownHosts, 0o600); err != nil {
		return err
	}
	if _, err := os.Lstat(m.Paths.SSHConfig); errors.Is(err, fs.ErrNotExist) {
		return m.WriteConfigEntries(nil)
	} else if err != nil {
		return fmt.Errorf("inspect the SSH configuration: %w", err)
	}
	return nil
}

// Initialize creates the managed key and SSH configuration if needed.
func (m Manager) Initialize() error {
	if err := m.Paths.Ensure(); err != nil {
		return err
	}
	if err := m.ensureKey(); err != nil {
		return err
	}
	if err := m.WriteConfig(); err != nil {
		return err
	}
	if err := ensureFile(m.Paths.KnownHosts, 0o600); err != nil {
		return err
	}
	return nil
}

func (m Manager) ensureKey() error {
	_, err := os.Stat(m.Paths.PrivateKey())
	if err == nil {
		return nil
	}
	if !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("inspect the SSH key: %w", err)
	}
	command := exec.Command(
		"ssh-keygen",
		"-q",
		"-t", "ed25519",
		"-N", "",
		"-C", "sandboxctl",
		"-f", m.Paths.PrivateKey(),
	)
	command.Stdin = os.Stdin
	command.Stdout = os.Stdout
	command.Stderr = os.Stderr
	if err := command.Run(); err != nil {
		return fmt.Errorf("create the SSH key: %w", err)
	}
	return nil
}

// WriteConfig replaces the managed configuration with the saved sandbox entries.
func (m Manager) WriteConfig() error {
	instances, err := (store.Store{Paths: m.Paths}).List()
	if err != nil {
		return err
	}
	var content strings.Builder
	content.WriteString("# Managed by sandboxctl. Do not edit this file.\n")
	for _, instance := range instances {
		if err := cmdutil.ValidateSandboxName(instance.Name); err != nil {
			return err
		}
		ip := net.ParseIP(instance.GuestIP)
		if ip == nil || ip.To4() == nil {
			return fmt.Errorf("sandbox %q has an invalid IPv4 address", instance.Name)
		}
		if instance.SSHUser == "" || strings.ContainsAny(instance.SSHUser, " \t\r\n\"\\") || strings.HasPrefix(instance.SSHUser, "-") {
			return fmt.Errorf("sandbox %q has an invalid SSH user", instance.Name)
		}
		if instance.SSHPort < 1 || instance.SSHPort > 65535 {
			return fmt.Errorf("sandbox %q has an invalid SSH port", instance.Name)
		}
		for _, path := range []string{m.Paths.PrivateKey(), m.Paths.KnownHosts} {
			if !filepath.IsAbs(path) || strings.ContainsAny(path, "\r\n") {
				return errors.New("SSH paths must be absolute and contain no line breaks")
			}
		}
		fmt.Fprintf(&content, `
Host sandboxctl-%s %s
    HostName %s
    User %s
    Port %d
    IdentityFile %s
    IdentitiesOnly yes
    UserKnownHostsFile %s
    GlobalKnownHostsFile /dev/null
    StrictHostKeyChecking ask
    CheckHostIP no
`, instance.Name, ip.String(), ip.String(), quoteConfigValue(instance.SSHUser), instance.SSHPort,
			quoteConfigValue(m.Paths.PrivateKey()), quoteConfigValue(m.Paths.KnownHosts))
	}
	file, err := os.CreateTemp(m.Paths.ConfigDir, ".ssh_config-*")
	if err != nil {
		return fmt.Errorf("create the temporary SSH configuration: %w", err)
	}
	defer os.Remove(file.Name())
	if _, err := file.WriteString(content.String()); err != nil {
		file.Close()
		return fmt.Errorf("write the SSH configuration: %w", err)
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := os.Rename(file.Name(), m.Paths.SSHConfig); err != nil {
		return fmt.Errorf("replace the SSH configuration: %w", err)
	}
	return nil
}

// WriteConfigEntries replaces the managed SSH fragment with daemon-owned entries.
func (m Manager) WriteConfigEntries(entries []HostEntry) error {
	if err := m.Paths.Ensure(); err != nil {
		return err
	}
	var content strings.Builder
	content.WriteString("# Managed by sandboxctl. Do not edit this file.\n")
	for _, entry := range entries {
		if err := cmdutil.ValidateSandboxName(entry.Name); err != nil {
			return err
		}
		ip := net.ParseIP(entry.Address)
		if ip == nil || ip.To4() == nil {
			return fmt.Errorf("sandbox %q has an invalid IPv4 address", entry.Name)
		}
		if entry.User == "" || strings.ContainsAny(entry.User, " \t\r\n\"\\") || strings.HasPrefix(entry.User, "-") {
			return fmt.Errorf("sandbox %q has an invalid SSH user", entry.Name)
		}
		for _, path := range []string{m.Paths.PrivateKey(), m.Paths.KnownHosts} {
			if !filepath.IsAbs(path) || strings.ContainsAny(path, "\r\n") {
				return errors.New("SSH paths must be absolute and contain no line breaks")
			}
		}
		fmt.Fprintf(&content, `
Host sandbox-%s %s
    HostName %s
    User %s
    Port 22
    IdentityFile %s
    IdentitiesOnly yes
    UserKnownHostsFile %s
    GlobalKnownHostsFile /dev/null
    StrictHostKeyChecking ask
    CheckHostIP no
`, entry.Name, ip.String(), ip.String(), quoteConfigValue(entry.User),
			quoteConfigValue(m.Paths.PrivateKey()), quoteConfigValue(m.Paths.KnownHosts))
	}
	file, err := os.CreateTemp(m.Paths.ConfigDir, ".ssh_config-*")
	if err != nil {
		return fmt.Errorf("create the temporary SSH configuration: %w", err)
	}
	defer os.Remove(file.Name())
	if err := file.Chmod(0o600); err != nil {
		_ = file.Close()
		return fmt.Errorf("set SSH configuration permissions: %w", err)
	}
	if _, err := file.WriteString(content.String()); err != nil {
		_ = file.Close()
		return fmt.Errorf("write the SSH configuration: %w", err)
	}
	if err := file.Close(); err != nil {
		return err
	}
	if err := os.Rename(file.Name(), m.Paths.SSHConfig); err != nil {
		return fmt.Errorf("replace the SSH configuration: %w", err)
	}
	return nil
}

// RefreshConfig rebuilds the SSH fragment from daemon-owned instance state.
func (m Manager) RefreshConfig(ctx context.Context, service controlpb.ControlServiceClient) error {
	response, err := service.ListInstances(ctx, &controlpb.ListInstancesRequest{})
	if err != nil {
		return fmt.Errorf("list sandbox instances: %w", err)
	}
	entries := make([]HostEntry, 0, len(response.GetInstances()))
	for _, instance := range response.GetInstances() {
		entries = append(entries, HostEntry{Name: instance.GetName(), Address: instance.GetGuestIp(), User: instance.GetSshUser()})
	}
	return m.WriteConfigEntries(entries)
}

// IncludeBlock returns the block for the user's SSH configuration.
func (m Manager) IncludeBlock() (string, error) {
	if !filepath.IsAbs(m.Paths.SSHConfig) || strings.ContainsAny(m.Paths.SSHConfig, "\r\n") {
		return "", errors.New("the SSH configuration path must be absolute and contain no line breaks")
	}
	return "Host *\n    Include " + quoteConfigValue(m.Paths.SSHConfig) + "\n", nil
}

// Exec replaces the current process with an SSH session to instance.
func (m Manager) Exec(instance model.Instance, remoteCommand []string) error {
	arguments := []string{
		"ssh",
		"-F", m.Paths.SSHConfig,
		"-p", fmt.Sprintf("%d", instance.SSHPort),
		instance.SSHUser + "@" + instance.GuestIP,
	}
	arguments = append(arguments, remoteCommand...)
	return syscall.Exec("/usr/bin/ssh", arguments, os.Environ())
}

func ensureFile(path string, mode fs.FileMode) error {
	file, err := os.OpenFile(path, os.O_CREATE|os.O_APPEND, mode)
	if err != nil {
		return fmt.Errorf("create %s: %w", path, err)
	}
	return file.Close()
}

func quoteConfigValue(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, `"`, `\"`)
	return `"` + value + `"`
}
